import {expect,test} from "@playwright/test";
import {execFile} from "node:child_process";
import {promisify} from "node:util";
import {readFile} from "node:fs/promises";
import {join} from "node:path";
import {ready} from "./workspace-helpers";

test("MCP proposal review preserves results until acceptance, supports undo and refuses content conflicts", async({page},info)=>{
  test.setTimeout(120000);
  const output=info.outputPath("proposal-artifacts");
  await promisify(execFile)("uv",["run","--extra","mcp","python","scripts/validate_mcp.py","--output-dir",output],{timeout:45000});
  await ready(page);
  await page.getByLabel("Arquivo do modelo").setInputFiles(join(output,"valid.model.json"));
  await expect(page.locator("h1")).toHaveText("Circuito resistivo via MCP");
  await page.keyboard.press("F5");
  await expect(page.getByTestId("finding-count")).toHaveText("0",{timeout:20000});
  await page.getByLabel("Arquivo de proposta").setInputFiles(join(output,"known-defect.proposal.json"));
  const dialog=page.getByRole("dialog",{name:"Revisar proposta",exact:true});
  await expect(dialog.getByText("reference · Alterado")).toBeVisible({timeout:20000});
  await page.screenshot({path:info.outputPath("proposal-review.png")});
  await expect(page.getByTestId("finding-count")).toHaveText("0");
  await expect(dialog.getByRole("button",{name:"Aplicar proposta"})).toBeDisabled();
  await dialog.getByRole("button",{name:"Cancelar",exact:true}).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByTestId("finding-count")).toHaveText("0");
  await page.getByLabel("Arquivo de proposta").setInputFiles(join(output,"known-defect.proposal.json"));
  await expect(dialog.getByText("reference · Alterado")).toBeVisible({timeout:20000});
  await dialog.getByRole("checkbox").check();
  await dialog.getByRole("button",{name:"Aplicar proposta"}).click();
  await expect(dialog).toBeHidden({timeout:20000});
  await expect(page.getByTestId("finding-count")).toHaveText("—");
  await page.keyboard.press("F5");
  await expect(page.getByTestId("finding-count")).toHaveText("1",{timeout:20000});
  await page.keyboard.press("Control+z");
  await expect(page.getByTestId("finding-count")).toHaveText("—");
  await page.keyboard.press("F5");
  await expect(page.getByTestId("finding-count")).toHaveText("0",{timeout:20000});
  await page.locator(".file-menu > summary").click();
  await page.getByRole("button",{name:"Registro de propostas…",exact:true}).click();
  const journal=page.getByRole("dialog",{name:"Registro de propostas",exact:true});
  await expect(journal.getByTestId("proposal-decision")).toHaveCount(1);
  await expect(journal.getByTestId("proposal-decision")).toHaveAttribute("data-state","applied");
  await journal.getByTestId("proposal-decision").locator("summary").first().click();
  await expect(journal.getByText("Aplicada naquela sessão.",{exact:false})).toBeVisible();
  const exported=page.waitForEvent("download");
  await journal.getByRole("button",{name:"Exportar registro"}).click();
  const record=JSON.parse(await readFile((await (await exported).path())!,"utf8"));
  expect(record.record.state).toBe("applied");expect(record.record.proposal.candidate_model.observations[0].value).toBe(13);
  await journal.getByRole("button",{name:"Fechar",exact:true}).click();
  await page.getByLabel("Arquivo de proposta").setInputFiles(join(output,"known-defect.proposal.json"));
  await expect(dialog.getByText("reference · Alterado")).toBeVisible({timeout:20000});
  await dialog.getByRole("button",{name:"Rejeitar proposta"}).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByTestId("finding-count")).toHaveText("0");
  await page.reload();
  await expect(page.locator("h1")).toBeVisible({timeout:20000});
  await page.getByLabel("Arquivo do modelo").setInputFiles(join(output,"valid.model.json"));
  await expect(page.locator("h1")).toHaveText("Circuito resistivo via MCP");
  await page.locator(".file-menu > summary").click();
  await page.getByRole("button",{name:"Registro de propostas…",exact:true}).click();
  await expect(journal.getByTestId("proposal-decision")).toHaveCount(2);
  await expect(journal.locator('[data-state="rejected"]')).toHaveCount(1);
  await expect(journal.locator('[data-state="applied"]')).toHaveCount(1);
  await page.screenshot({path:info.outputPath("proposal-journal.png")});
  await journal.getByRole("button",{name:"Fechar",exact:true}).click();
  await page.keyboard.press("F5");
  await expect(page.getByTestId("finding-count")).toHaveText("0",{timeout:20000});
  const wrong=JSON.parse(await readFile(join(output,"known-defect.proposal.json"),"utf8"));
  wrong.base_model.variables[0].value=99; // Keep sender hash unchanged: content must decide.
  await page.getByLabel("Arquivo de proposta").setInputFiles({name:"stale.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(wrong))});
  await expect(dialog.getByRole("alert")).toContainText("não corresponde",{timeout:20000});
  await expect(dialog.getByRole("button",{name:"Aplicar proposta"})).toBeDisabled();
  await expect(page.getByTestId("finding-count")).toHaveText("0");
});
